#!/usr/bin/env bash
# 只打印"换成域名要改什么"，不写任何文件。
#
#   bash deploy/show-domain-config.sh ai.math.whu.edu.cn
#
# 为什么做成"打印"而不是"自动改"：nginx 配置一旦写错，整站 502/404，
# 而错在哪一行往往看不出来。打印出来由人粘贴、sudo nginx -t 验证，比脚本猜着改安全。

set -uo pipefail

DOMAIN="${1:-}"
if [ -z "$DOMAIN" ]; then
  echo "用法：bash deploy/show-domain-config.sh 你的域名"
  echo "例如：bash deploy/show-domain-config.sh ai.math.whu.edu.cn"
  exit 2
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

cat <<EOF
================================================================================
域名：$DOMAIN
仓库：$ROOT
================================================================================

【第 0 步】先确认域名已经解析到这台机器（没解析好就往下做，会把站弄挂）
    dig +short $DOMAIN
    期望输出：115.156.72.1（或这台机器的公网地址）

================================================================================
【第 1 步】nginx 里已经在用的 server 块，只改一处
================================================================================
文件：/etc/nginx/sites-available/whu-teaching

现在这一行是（接受任意 Host，所以域名解析过来就能用）：
    server_name _;

改成：
    server_name $DOMAIN;

================================================================================
【第 2 步】想让地址栏"永远不出现 IP"：加一个跳转块
================================================================================
把下面整段追加到同一个文件的末尾。用 IP 访问时 301 到域名，
用域名访问不受影响。

注意：**必须先确认第 0 步的 dig 有输出**。域名没解析就加这段，
浏览器会跳到"打不开的域名"，等于把站锁死。

    server {
        listen 80 default_server;
        server_name _;
        return 301 https://$DOMAIN\$request_uri;
    }

如果暂时只有 http（没有证书），把 https:// 改成 http://，否则会跳到不存在的 443。

================================================================================
【第 3 步】https：证书与 443
================================================================================
有证书之后，用仓库里的模板（80 只留证书验证并跳转、443 带 HSTS）：

    sudo cp $ROOT/deploy/nginx-tls.conf.example /etc/nginx/sites-available/whu-teaching
    sudo nano /etc/nginx/sites-available/whu-teaching
    # 把里面所有 ai.math.example.edu.cn 替换成 $DOMAIN

如果学校统一签发证书，把证书放到 /etc/nginx/ssl/ 并把模板里
ssl_certificate / ssl_certificate_key 两行改成实际路径。

================================================================================
【第 4 步】应用配置（.env 只有两行要动）
================================================================================
    nano $ROOT/.env

        CORS_ORIGINS=https://$DOMAIN     # 原来是 http://115.156.72.1
        # 删掉 COOKIE_SECURE=0 这一行（上 https 后自动带 Secure）

    sudo nginx -t && sudo systemctl reload nginx
    sudo systemctl restart whu-teaching

================================================================================
【第 5 步】验证（四条都要过）
================================================================================
    dig +short $DOMAIN                                  # → 服务器地址
    curl -sI http://$DOMAIN | head -1                     # → 301 或 200
    curl -s  https://$DOMAIN/api/v1/health                # → {"status":"ok",...}
    curl -sI http://115.156.72.1/ | head -1              # → 301（跳到域名）

然后浏览器登录一次，翻两页确认不掉线（cookie 能不能回传，只有真登录才知道）。

================================================================================
【没有域名时的两个替代】
================================================================================
A. 只让自己的电脑显示域名（演示够用，别人无效）：
    Windows 用管理员打开记事本，编辑
        C:\\Windows\\System32\\drivers\\etc\\hosts
    加一行（前面的地址换成服务器实际地址）：
        115.156.72.1   $DOMAIN
    之后浏览器访问 http://$DOMAIN 即可。因为 nginx 是 server_name _，
    它不挑 Host，所以这条立刻生效。

B. 让校内所有人用域名访问（不需要放行公网）：
    请网络中心加一条**校内 DNS A 记录**：$DOMAIN → 115.156.72.1。
    这解决"网址不是 IP"，但不解决"校外打不开"——那要单独申请入站 443。

================================================================================
【顺序提醒】
================================================================================
    1. 网络中心：校内 DNS 记录（当天可办）
    2. 网络中心：入站 443 放行（1～3 周）
    3. 证书（学校签发，或 certbot）
    4. 第 1～4 步改配置
    5. 第 5 步验证

先做 4 再等 2，会得到一个"校内能开、校外打不开"的域名——那也没问题，
只是别以为域名一到校外就通了。
EOF
